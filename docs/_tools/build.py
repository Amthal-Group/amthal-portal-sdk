#!/usr/bin/env python3
"""Regenerate the shared shell of every documentation page.

The site itself has no build step — it is a folder of static files served as-is, which is why
every asset reference is relative and nothing fetches from a network. This tool is an AUTHORING
convenience, not a deployment step: it rewrites the parts of each page that must be identical
everywhere (head, header, sidebar, on-page contents, footer) so that adding a page or renaming a
section does not mean hand-editing six files and getting five of them slightly wrong.

Run it after editing any page's headings, or after adding a page to nav.json:

    python3 _tools/build.py            # rewrite
    python3 _tools/build.py --check    # exit 1 if anything is stale (for CI)

Everything between the @shell markers is generated and will be overwritten. Everything inside
<main> is hand-written and is never touched, except that headings missing an id are given one so
they can be linked and tracked by the contents rail.
"""

from __future__ import annotations

import argparse
import hashlib
import html
import json
import re
import sys
import unicodedata
from pathlib import Path

import highlight

DOCS = Path(__file__).resolve().parent.parent
NAV = json.loads((Path(__file__).resolve().parent / "nav.json").read_text(encoding="utf-8"))

BEGIN = "<!-- @shell:{} — generated by _tools/build.py, do not edit by hand -->"
END = "<!-- @/shell:{} -->"


# --------------------------------------------------------------------------- helpers

def slug(text: str) -> str:
    """A stable, readable id from heading text."""
    text = html.unescape(re.sub(r"<[^>]+>", "", text))
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    text = re.sub(r"[^\w\s-]", "", text).strip().lower()
    return re.sub(r"[-\s]+", "-", text)[:60].strip("-")


def text_of(fragment: str) -> str:
    """Heading text with tags stripped but entities left intact for re-emission."""
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", fragment)).strip()


def split_page(src: str) -> dict:
    """Break a page into the regions this tool owns and the one it must not touch."""
    head = re.search(r"<head>(.*?)</head>", src, re.S)
    main = re.search(r"(<main\b[^>]*>)(.*?)(</main>)", src, re.S)
    if not head or not main:
        raise SystemExit("page is missing <head> or <main>")
    return {"head": head.group(1), "main_open": main.group(1), "main": main.group(2)}


# --------------------------------------------------------------------------- headings

def ensure_heading_ids(body: str) -> tuple[str, list[dict]]:
    """Give every h2/h3 a linkable id and return the resulting section tree.

    An h2 wrapped in <section id="x"> already has a target, and existing ids are load-bearing —
    the anchor lists and cross-page links point at them — so they are preserved exactly. Only
    headings with nothing to link to acquire one.
    """
    used: set[str] = set(re.findall(r'id="([^"]+)"', body))
    tree: list[dict] = []
    out: list[str] = []
    cursor = 0
    section_id: str | None = None

    pattern = re.compile(r'<section\b([^>]*)>|<(h2|h3)\b([^>]*)>(.*?)</\2>', re.S)
    for m in pattern.finditer(body):
        out.append(body[cursor:m.start()])
        cursor = m.end()

        if m.group(1) is not None:                       # a <section ...> opening tag
            found = re.search(r'id="([^"]+)"', m.group(1))
            section_id = found.group(1) if found else None
            out.append(m.group(0))
            continue

        level, attrs, inner = m.group(2), m.group(3), m.group(4)
        existing = re.search(r'id="([^"]+)"', attrs)

        if existing:
            anchor = existing.group(1)
        elif level == "h2" and section_id:
            anchor = section_id                          # the wrapper already carries the target
            section_id = None
        else:
            base = slug(inner) or f"{level}-{len(tree)}"
            anchor = base
            n = 2
            while anchor in used:
                anchor, n = f"{base}-{n}", n + 1
            used.add(anchor)
            attrs = f'{attrs} id="{anchor}"'

        tree.append({"level": level, "id": anchor, "text": text_of(inner)})
        out.append(f"<{level}{attrs}>{inner}</{level}>")

    out.append(body[cursor:])
    return "".join(out), tree


# --------------------------------------------------------------------------- content invariants

def normalise_content(body: str) -> str:
    """Fix the structural mistakes that are easy to make by hand and impossible to see in source.

    Each of these was found rendering wrongly on the live site, and each is mechanical, so the
    generator enforces it rather than trusting six pages to stay in agreement.
    """
    # A bare <table class="table"> has no scroll container. `.table` is width:100% with auto
    # layout, and the stylesheet forces white-space:nowrap on header cells and in-cell <code>, so
    # its min-content width can exceed 1200px. Nothing above it scrolls, so the overflow reaches
    # the viewport and the WHOLE PAGE scrolls sideways on a phone, dragging every paragraph with
    # it. Wrapping is the stylesheet's own intended pattern.
    def wrap_tables(text: str) -> str:
        parts = re.split(r'(<table class="table">.*?</table>)', text, flags=re.S)
        out: list[str] = []
        for part in parts:
            if part.startswith('<table class="table">') and not (
                    out and out[-1].rstrip().endswith('<div class="table-scroll">')):
                out.append(f'<div class="table-scroll">{part}</div>')
            else:
                out.append(part)
        return "".join(out)

    body = wrap_tables(body)

    # A horizontally scrollable region must be reachable by keyboard; without tabindex a keyboard
    # user simply cannot read the right-hand end of a long code line.
    body = re.sub(r'<pre class="code">', '<pre class="code" tabindex="0">', body)

    # .seq__row is a two-column grid whose FIRST item is the generated counter. Any row with more
    # than one child therefore auto-places its second, fourth… child into the 44px number column,
    # which is what renders a paragraph one word per line. Forcing every real child into column 2
    # fixes every row at once, including ones written later.
    # (Implemented in the stylesheet as `.seq__row > * { grid-column: 2 }` — see site.css.)

    # The .seq counter already draws the number in its own badge, so a literal "1. " written
    # into the step's title renders it twice. Steps are titled with <h3> on some pages and
    # <strong> on others, so strip the prefix from both — but only inside a .seq row, where the
    # counter exists. A numbered heading anywhere else is the author's own numbering.
    def drop_double_number(m):
        return re.sub(r'(<(?:h3|strong)[^>]*>)\s*\d+\.\s+', r'\1', m.group(0))
    body = re.sub(r'<div class="seq__row">.*?</div>', drop_double_number, body, flags=re.S)
    return body


# --------------------------------------------------------------------------- search

def index_entries(page: dict, body: str, tree: list[dict]) -> list[dict]:
    """One search record per section: its heading, its page, and the prose under it.

    Built here rather than in the browser, because the only other way for a static site to know
    its own contents is to fetch and parse every page on the reader's first keystroke.
    """
    plain = re.sub(r"<(script|style|pre)\b.*?</\1>", " ", body, flags=re.S)
    # Slice from the END of the tag that carries the id — starting at the attribute itself would
    # spill the rest of the opening tag into the excerpt.
    cuts = {}
    for m in re.finditer(r'id="([^"]+)"', plain):
        close = plain.find(">", m.end())
        if close != -1:
            cuts[close + 1] = m.group(1)

    out, positions = [], sorted(cuts)
    for i, start in enumerate(positions):
        end = positions[i + 1] if i + 1 < len(positions) else len(plain)
        node = next((n for n in tree if n["id"] == cuts[start]), None)
        if not node:
            continue
        text = html.unescape(re.sub(r"<[^>]+>", " ", plain[start:end]))
        text = re.sub(r"\s+", " ", text).strip()
        if len(text) < 12:
            continue
        out.append({
            "p": page["file"],
            "pt": page["nav"],
            "h": node["text"],
            "id": node["id"],
            "l": 2 if node["level"] == "h2" else 3,
            "t": text[:340],
        })
    return out


# --------------------------------------------------------------------------- regions

def asset(path: str) -> str:
    """An asset URL stamped with a short hash of its contents.

    The site sits behind a CDN with a four-hour TTL, so a redeploy that reuses a filename is
    served stale: the pages arrive new and their stylesheet arrives old, which renders the
    layout as an unstyled list until the cache expires. A URL that changes when the bytes change
    cannot be served stale, and needs no cache purge on deploy.
    """
    f = DOCS / path
    if not f.exists():
        return path
    return f"{path}?v={hashlib.sha256(f.read_bytes()).hexdigest()[:10]}"


def render_head(page: dict, site: dict) -> str:
    """The <head>. Identical everywhere except title, description and canonical URL."""
    title = html.escape(page["title"])
    desc = html.escape(page["description"])
    canonical = site["url"].rstrip("/") + "/" + page["file"]
    # Absolute, because a scraper resolves it out of context — but still versioned:
    # Slack, Teams and X cache a card image far longer than the page that names it.
    social = site["url"].rstrip("/") + "/" + asset(site["card"])
    return f"""<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<meta name="description" content="{desc}">
<link rel="canonical" href="{canonical}">

<meta property="og:type" content="website">
<meta property="og:site_name" content="{html.escape(site['name'])}">
<meta property="og:title" content="{title}">
<meta property="og:description" content="{desc}">
<meta property="og:url" content="{canonical}">
<meta property="og:image" content="{social}">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="{title}">
<meta name="twitter:description" content="{desc}">
<meta name="twitter:image" content="{social}">

<meta name="theme-color" content="#121e4c">
<link rel="icon" href="{asset("assets/img/favicon.svg")}" type="image/svg+xml">
<link rel="apple-touch-icon" href="{asset("assets/img/apple-touch-icon.png")}">
<link rel="stylesheet" href="{asset("assets/css/site.css")}">"""


