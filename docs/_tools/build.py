# --------------------------------------------------------------------------- assembly

def marked(name: str, content: str) -> str:
    return f"{BEGIN.format(name)}\n{content}\n{END.format(name)}"


def build_page(page: dict, site: dict) -> str:
    src = (DOCS / page["file"]).read_text(encoding="utf-8")
    parts = split_page(src)

    # The in-content "On this page" blocks are superseded by the contents rail; two lists of the
    # same links, one of them not tracking the reader's position, is worse than one. Strip them
    # BEFORE reading the heading tree — one of them wraps a heading of its own, so removing them
    # afterwards would change the tree the rail was built from and take a second pass to settle.
    body = re.sub(r'\s*<nav class="anchor-list" aria-label="On this page">.*?</nav>\n?',
                  "\n", parts["main"], flags=re.S)
    body = re.sub(r'\s*<nav aria-label="On this page">.*?</nav>\n?', "\n", body, flags=re.S)

    body = normalise_content(body)
    body, painted = highlight.apply(body)
    body, tree = ensure_heading_ids(body)
    records = index_entries(page, body, tree)
    page["_painted"] = painted

    return records, f"""<!DOCTYPE html>
<html lang="en">
<head>
{marked('head', render_head(page, site))}
</head>
<body>

{marked('header', render_header(page, site))}

<div class="layout">
{marked('sidebar', render_sidebar(page, tree, site))}

<main class="content" id="main">
{body.strip()}
</main>

{marked('toc', render_toc(tree))}
</div>

{marked('footer', render_footer(site))}

</body>
</html>
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="report stale pages and exit non-zero instead of rewriting")
    args = ap.parse_args()

    site, stale = NAV["site"], []
    present = [p for p in NAV["pages"] if (DOCS / p["file"]).exists()]
    for page in NAV["pages"]:
        if page not in present:
            print(f"  skip   {page['file']} (not written yet)")

    # Two passes, because the pages carry a content hash of the search index and the index is
    # built from the pages. Pass one exists only to settle the index; pass two renders against
    # the final hash, so a single run is already idempotent.
    index: list[dict] = []
    for page in present:
        records, _ = build_page(page, site)
        index.extend(records)

    index_path = DOCS / "assets" / "search-index.json"
    payload = json.dumps(index, ensure_ascii=False, separators=(",", ":")) + "\n"
    index_current = index_path.exists() and index_path.read_text(encoding="utf-8") == payload
    if index_current:
        print(f"  ok     assets/search-index.json ({len(index)} sections)")
    elif args.check:
        print("  STALE  assets/search-index.json")
        stale.append("assets/search-index.json")
    else:
        index_path.write_text(payload, encoding="utf-8")
        print(f"  wrote  assets/search-index.json ({len(index)} sections)")

    for page in present:
        path = DOCS / page["file"]
        _, new_html = build_page(page, site)
        if path.read_text(encoding="utf-8") == new_html:
            print(f"  ok     {page['file']}")
            continue
        stale.append(page["file"])
        if args.check:
            print(f"  STALE  {page['file']}")
        else:
            path.write_text(new_html, encoding="utf-8")
            print(f"  wrote  {page['file']} ({page.get('_painted', 0)} code blocks highlighted)")

    listed = [p for p in NAV["pages"] if p.get("listed", True)
              and (DOCS / p["file"]).exists()]
    base = site["url"].rstrip("/")
    urls = "\n".join(
        f"  <url><loc>{base}/{p['file']}</loc></url>" for p in listed)
    extra = {
        "sitemap.xml": f'''<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
{urls}
</urlset>
''',
        "robots.txt": f"User-agent: *\nAllow: /\n\nSitemap: {base}/sitemap.xml\n",
    }
    for name, body in extra.items():
        path = DOCS / name
        if path.exists() and path.read_text(encoding="utf-8") == body:
            print(f"  ok     {name}")
        elif args.check:
            print(f"  STALE  {name}")
            stale.append(name)
        else:
            path.write_text(body, encoding="utf-8")
            print(f"  wrote  {name}")

    if args.check and stale:
        print(f"\n{len(stale)} page(s) stale — run: python3 _tools/build.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
