def render_sidebar(current: dict, tree: list[dict], site: dict) -> str:
    """Every page, grouped, with the current page's sections expanded beneath it."""
    groups: list[tuple[str, list[dict]]] = []
    for p in NAV["pages"]:
        if not p.get("listed", True):
            continue
        if not groups or groups[-1][0] != p["group"]:
            groups.append((p["group"], []))
        groups[-1][1].append(p)

    out = ['<aside class="sidebar" id="sidebar" data-sidebar>',
           '  <nav class="sidebar__nav" aria-label="Documentation">']
    for name, pages in groups:
        out.append(f'    <p class="sidebar__group">{html.escape(name)}</p>')
        out.append('    <ul class="sidebar__list">')
        for p in pages:
            here = p["file"] == current["file"]
            cur = ' aria-current="page"' if here else ""
            out.append(f'      <li><a href="./{p["file"]}"{cur}>{html.escape(p["nav"])}</a>')
            if here:
                sections = [n for n in tree if n["level"] == "h2"]
                if sections:
                    out.append('        <ul class="sidebar__sections">')
                    for s in sections:
                        out.append(
                            f'          <li><a href="#{s["id"]}">{html.escape(s["text"])}</a></li>')
                    out.append('        </ul>')
            out.append('      </li>')
        out.append('    </ul>')
    out.append('  </nav>')
    out.append(f'''  <p class="sidebar__meta">
    SDK {site["sdkVersion"]} · Bridge protocol v{site["protocol"]}<br>
    <a href="{site["repo"]}" rel="noopener">GitHub</a> ·
    <a href="{site["repo"]}/issues" rel="noopener">Issues</a>
  </p>''')
    out.append('</aside>')
    return "\n".join(out)


def render_toc(tree: list[dict]) -> str:
    """The contents rail. Empty pages get an empty rail rather than a broken one."""
    items = [n for n in tree if n["level"] in ("h2", "h3")]
    if len(items) < 3:
        return '<div class="toc" aria-hidden="true"></div>'
    out = ['<nav class="toc" aria-labelledby="toc-title" data-toc>',
           '  <p class="toc__title" id="toc-title">On this page</p>',
           '  <ul>']
    for n in items:
        cls = ' class="toc__sub"' if n["level"] == "h3" else ""
        out.append(f'    <li{cls}><a href="#{n["id"]}">{html.escape(n["text"])}</a></li>')
    out.append('  </ul>')
    out.append('</nav>')
    return "\n".join(out)


